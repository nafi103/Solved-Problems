vector<int> fibo = {1,1};

void solve()
{
    string ans = "";
    int n;
    cin>>n;
    for(int i = 0; i<sz(fibo); i++){
        if(fibo[i]<=n){
            n-=fibo[i];
            ans.push_back('1');
        }else{
            if(sz(ans))
                ans.push_back('0');
        }
    }
    cout<<ans<<endl;
}

