const int n = 5e6+10;
vector<int> phi(n + 1);

void phi_1_to_n() {
    for (int i = 0; i <= n; i++)
        phi[i] = i;

    for (int i = 2; i <= n; i++) {
        if (phi[i] == i) {
            for (int j = i; j <= n; j += i)
                phi[j] -= phi[j] / i;
        }
    }

    for(int i = 1; i<n; i++){
        phi[i]*=phi[i];
        phi[i]+=phi[i-1];
    }
}

void solve()
{
    long long a,b;
    cin>>a>>b;
    cout<<phi[b] - phi[a-1]<<endl;
}

