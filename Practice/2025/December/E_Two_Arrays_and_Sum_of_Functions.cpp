const int N = 2e5 + 10;
int n, a[N], b[N], ans;

void input(){
    ans = 0;
    cin >> n;
    for(int i = 0; i < n; i++)
        cin >> a[i];
    for(int i = 0; i < n; i++)
        cin >> b[i];
}

void solve()
{
    input();

    for(int i = 0; i < n; i++){
        a[i] = (a[i] * (i + 1) * (n - i));
    }

    sort(a, a + n);
    sort(b, b + n, greater<int>());

    for(int i = 0; i < n; i++){
        a[i] %= mod;
        ans = (ans + (a[i] * b[i]) % mod) % mod;
    }
    cout << ans << endl;
}

