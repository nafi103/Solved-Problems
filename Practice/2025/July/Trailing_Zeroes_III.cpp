void solve()
{
    int n;
    cin>>n;
    int ans = inf;
    int l = 5, r = 1e10;
    while(l<=r){
        int mid = (l+r)/2;
        int fives = mid/5;
        for(int i = 5*5; i<=mid; i*=5){
            fives+=mid/i;
        }
        if(fives>=n){
            if(fives==n)
                ans=min(ans,mid);
            r = mid-1;
        }else{
            l = mid+1;
        }
    }
    if(ans==inf)
        cout<<"impossible"<<endl;
    else
        cout<<ans<<endl;
}

