void solve()
{
    int n;
    cin>>n;
    vector<int>a(n),b(n);
    readv(a);readv(b);
    if(a[n-1]!=b[n-1]){
        no;
        return;
    }
    for(int i = 0; i<n-1; i++){
        if(a[i]!=b[i] and (a[i]^a[i+1])==b[i])
            a[i] = b[i];
    }
    for(int i = n-2; i>=0; i--){
        if(a[i]!=b[i] and (a[i]^a[i+1])==b[i]){
            a[i] = b[i];
        }else if(a[i]!=b[i]){
            no;
            return;
        }
    }
    yes;
}

