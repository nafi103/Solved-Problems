void solve()
{
    int a, b, x;
    cin >> a >> b >> x;

    int ans = inf;

    int op = 0;
    while(a > 0 or b > 0){
        ans = min(ans, op + abs(a - b));
        if(b < a)
            swap(a, b);
        b /= x;
        op++;
    }
    ans = min(ans, op);

    cout << ans << endl;
}

