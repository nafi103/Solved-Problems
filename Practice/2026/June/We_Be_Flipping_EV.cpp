void solve()
{
    int n;
    cin >> n;
    vector<int> ans, arr(n);
    for(auto &x: arr)
        cin >> x;

    for(int i = n - 1, p = 0; i >= 0; i--){
        int flip = (arr[i] > 0);

        if((flip and !p) or (!flip and p)){
            p ^= 1;
            ans.push_back(i + 1);
        }
    }

    cout << sz(ans) << endl;
    for(auto &x: ans)
        cout << x << " ";
    cout << endl;
}

