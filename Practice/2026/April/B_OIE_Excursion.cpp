void solve()
{
    int n, m;
    cin >> n >> m;
    bool flag = true;
    int last = inf, cnt = 0;
    for(int i = 0, x; i < n; i++){
        cin >> x;
        if(x == last){
            cnt++;
        }else{
            cnt = 1;
        }
        last = x;
        if(cnt >= m){
            flag = false;
        }
    }
    if(flag)
        cout << "YES" << endl;
    else
        cout << "NO" << endl;
}

