int d(int x){
    int s = 0;
    while(x > 0){
        s += x % 10;
        x /= 10;
    }
    return s;
}

void solve()
{
    int x;
    cin >> x;
    int ans = 0;
    for (int y = x + 1000; y >= x; y--){
        if(y - d(y) == x)
            ans++;
    }
    cout << ans << endl;
}

