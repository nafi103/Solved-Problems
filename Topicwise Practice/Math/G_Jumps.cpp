void solve()
{
    int x;
    cin>>x;
    int n = (sqrt(8*x+1) - 1)/2;
    if(n*(n+1)==2*x){
        cout<<n<<endl;
        return;
    }
    if(n*(n+1)<2*x)
        n++;
    int curr_value = (n*(n+1))/2;
    for(int i = curr_value-x-1; i>0;  i--){
        if(curr_value-(i+1)>=x)
            curr_value-=(i+1);
        i = curr_value-x;
    }
    if(curr_value>x)
        n+=curr_value-x;
    cout<<n<<endl;
}

