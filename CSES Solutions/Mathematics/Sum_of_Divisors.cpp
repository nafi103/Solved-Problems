int expo(int a, int b, int m) {int res = 1; a%=m; while (b > 0) {if (b & 1)res = (res * a) % m; a = (a * a) % m; b = b >> 1;} return res;}
int mminvprime(int a, int b) {return expo(a, b - 2, b);}

int in2 = mminvprime(2,mod);

int sum_range(int l, int r){
    r--;
    l--;
    l%=mod;
    r%=mod;
    return ((((((r*(r+1))%mod) * in2)%mod - ((((l*(l+1))%mod) * in2)%mod))%mod) + mod)%mod;
}

void solve()
{
    int n,ans = 0;
    cin>>n;
    int i = 1,next,mult;
    while(i<n){
        mult = n/i;next = n/mult + 1;
        ans+=((sum_range(i,next)*mult)%mod);
        ans%=mod;
        i = next;
    }
    cout<<max(ans,1ll)<<endl;
}

