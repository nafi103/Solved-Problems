void solve()
{
    int n,k;
    cin>>n>>k;
    bool _begin = false;
    int _start = 1, _add = 1, _remove;
    while(k and n>1){
        if(_begin) _remove = (n+1)/2;
        else _remove = n/2;
        if(_remove>=k) break;
        if(_begin){
            _start+=_add;
            _begin = !(n&1);
        }else{
            _begin = (n&1);
        }
        n-=_remove;
        k-=_remove;
        _add<<=1;
    }
    if(!_begin and n>1){
        _start+=_add;
    }
    _add = _add*2;
    cout<<_start+((k-1)*_add)<<endl;
}

