void solve()
{
    int n,x;
    cin>>n>>x;
    vector<int>cost(n),page(n),dp(x+1,0),curr(x+1);
    readv(cost);
    readv(page);
    for(int i = 0; i<n; i++){
        for(int j = 0; j<=x; j++){
            curr[j] = max(dp[j],(j>=cost[i]?page[i]+dp[j-cost[i]]:-1));
        }
        dp = curr;
    }
    cout<<dp[x]<<endl;
}

