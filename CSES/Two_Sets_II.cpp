int expo(int a, int b, int m) {int res = 1; while (b > 0) {if (b & 1)res = (res * a) % m; a = (a * a) % m; b = b >> 1;} return res;}
int mminvprime(int a, int b) {return expo(a, b - 2, b);}

void solve()
{
    int n;
    cin>>n;
    int target = (n*(n+1))/2;
    if(target&1){
        cout<<0<<endl;
        return;
    }
    target>>=1;
    vector<int>dp(target+1,0),curr(target+1);
    dp[0] = 1;
    for(int i = 1; i<=n; i++){
        for(int j = 0; j<=target; j++){
            curr[j] = (dp[j]+(j>=i?dp[j-i]:0ll))%mod;
        }
        dp=curr;
    }
    cout<<(dp[target]*mminvprime(2,mod))%mod<<endl;
}

