void solve()
{
    int n,op = 0;
    cin>>n;
    string str;
    cin>>str;
    int l = 0, p = n-1, r = -1;
    while(l<n and str[l]!='1')
        l++;
    while(p>l){
        if(str[p]=='0' and (p==n-1 or str[p+1]=='1'))
            r = p;
        p--;
    }
    if(l<r){
        reverse(str.begin()+l, str.begin()+r+1);
    }
    for(int i = 0; i<n; i++){
        op++;
        if((i==0 and str[i]=='1') or (i and str[i]!=str[i-1]))
            op++;
    }
    cout<<op<<endl;
}

