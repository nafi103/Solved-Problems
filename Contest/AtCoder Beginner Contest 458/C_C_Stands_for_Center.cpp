void solve()
{
    int ans = 0;
    string str;
    cin >> str;
    int n = sz(str);
    for(int i = 0; i < n; i++){
        if(str[i] == 'C'){
            int left = i, right = n - 1 - i;
            ans += min(left, right) + 1;
        }
    }
    cout << ans << endl;
}

