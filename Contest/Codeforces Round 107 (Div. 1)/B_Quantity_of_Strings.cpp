int expo(int a, int b, int m) {int res = 1; while (b > 0) {if (b & 1)res = (res * a) % m; a = (a * a) % m; b = b >> 1;} return res;}


void solve()
{
    int n,m,k;
    cin>>n>>m>>k;
    if(k==1 or k>n){
        cout<<expo(m,n,mod)<<endl;
        return;
    }
    if(n==k){
        cout<<expo(m,(n+1)/2,mod)<<endl;
    }
    else if((k&1)==0){
        cout<<m<<endl;
    }
    else{
        cout<<m*m<<endl;
    }
}

