 void solve()
{
    int n,c,x;
    cin >> n >> c;
    int ans = ((c+1)*(c+2))/2;
    vector<int> cnt(2,0);
    for(int i = 0; i < n; i++){
        cin >> x;
        ans -= (c - x);
        ans -= (x + 2) / 2;
        ans += cnt[x & 1];
        cnt[x & 1]++;
    }
    cout << ans << endl;
}
