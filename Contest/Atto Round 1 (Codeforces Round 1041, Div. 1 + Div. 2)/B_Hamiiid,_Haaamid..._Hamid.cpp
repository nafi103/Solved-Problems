void solve()
{
    int n,ini;
    cin>>n>>ini;
    ini--;
    string str;
    cin>>str;
    if(ini==0 or ini==n-1){
        cout<<1<<endl;
        return;
    }
    int l = ini,r = ini;
    while(l>=0 and str[l]=='.')
        l--;
    while(r<n and str[r]=='.')
        r++;
    int left = l+1, right = n-r;
    cout<<min({max({1ll,left+1,right+1}),ini+1,n-ini})<<endl;
}

