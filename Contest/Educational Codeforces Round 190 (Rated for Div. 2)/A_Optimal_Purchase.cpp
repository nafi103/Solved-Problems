 void solve()
{
    int n, a, b;
    cin >> n >> a >> b;
    if(a * 3 <= b){
        cout << n * a << endl;
        return;
    }
    int cost = (n / 3) * b;
    int rem = n % 3;
    if(rem * a > b){
        cost += b;
    }else{
        cost += rem * a;
    }
    cout << cost << endl;
}
