void solve()
{
	string str;
	cin >> str;
    stack<char> st;
    for(char &x: str){
    	if(!st.empty() and st.top() == x){
    		st.pop();
    	}else{
    		st.push(x);
    	}
    }
    if(st.empty())
    	cout << "YES" << endl;
    else
    	cout << "NO" << endl;
}

